package com.codeinsight.model;

public class DataStructureSnapshot {
    private Object arraySnapshot;
    private Object linkedListSnapshot;
    private Object treeSnapshot;
    private Object graphSnapshot;
    private Object queueSnapshot;
    private Object stackSnapshot;
    private Object heapSnapshot;

    public DataStructureSnapshot() {}

    public Object getArraySnapshot() {
        return arraySnapshot;
    }

    public void setArraySnapshot(Object arraySnapshot) {
        this.arraySnapshot = arraySnapshot;
    }

    public Object getLinkedListSnapshot() {
        return linkedListSnapshot;
    }

    public void setLinkedListSnapshot(Object linkedListSnapshot) {
        this.linkedListSnapshot = linkedListSnapshot;
    }

    public Object getTreeSnapshot() {
        return treeSnapshot;
    }

    public void setTreeSnapshot(Object treeSnapshot) {
        this.treeSnapshot = treeSnapshot;
    }

    public Object getGraphSnapshot() {
        return graphSnapshot;
    }

    public void setGraphSnapshot(Object graphSnapshot) {
        this.graphSnapshot = graphSnapshot;
    }

    public Object getQueueSnapshot() {
        return queueSnapshot;
    }

    public void setQueueSnapshot(Object queueSnapshot) {
        this.queueSnapshot = queueSnapshot;
    }

    public Object getStackSnapshot() {
        return stackSnapshot;
    }

    public void setStackSnapshot(Object stackSnapshot) {
        this.stackSnapshot = stackSnapshot;
    }

    public Object getHeapSnapshot() {
        return heapSnapshot;
    }

    public void setHeapSnapshot(Object heapSnapshot) {
        this.heapSnapshot = heapSnapshot;
    }
}
